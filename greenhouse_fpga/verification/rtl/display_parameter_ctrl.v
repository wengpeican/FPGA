// Independent controls: B1 button, C8/C7 active-low DIP switches.
// All state and frame snapshots belong to the existing pixel clock domain.
module display_parameter_ctrl #(parameter CLK_HZ=25000000)(
 input clk,rst,frame_tick,key_n,input [1:0] sw_n,
 output reg [7:0] volume,output reg [3:0] vol_level,brightness,contrast,
 output reg [1:0] selected,output reg hud_show);
 wire tap,hold;
 osd_button #(.CLK_HZ(CLK_HZ)) button(clk,rst,key_n,tap,hold);
 reg [1:0] sw_meta,sw_sync,sw_stable;
 reg [31:0] db_count,show_count;
 reg [3:0] vol_pending,bri_pending,con_pending;
 localparam DB=(CLK_HZ/1000)*20;
 function [7:0] gain;input [3:0] level;begin
 case(level)
 0:gain=0;1:gain=26;2:gain=51;3:gain=77;4:gain=102;5:gain=128;
 6:gain=153;7:gain=179;8:gain=204;9:gain=230;default:gain=255;
 endcase end endfunction
 always @(posedge clk or posedge rst)begin
 if(rst)begin
 sw_meta<=0;sw_sync<=0;sw_stable<=0;db_count<=0;show_count<=0;
 vol_pending<=5;bri_pending<=4;con_pending<=4;
 volume<=128;vol_level<=5;brightness<=4;contrast<=4;selected<=0;hud_show<=0;
 end else begin
 sw_meta<=~sw_n;sw_sync<=sw_meta;
 if(show_count!=0)show_count<=show_count-1'b1;
 if(sw_sync==sw_stable)db_count<=0;
 else if(db_count>=DB-1)begin
 sw_stable<=sw_sync;db_count<=0;show_count<=CLK_HZ*3;
 end else db_count<=db_count+1'b1;
 // Reject button events while switches are changing/debouncing.
 if((tap || hold) && sw_sync==sw_stable)begin
 show_count<=CLK_HZ*3;
 case(sw_stable)
 0:if(hold)begin if(vol_pending!=0)vol_pending<=vol_pending-1'b1;end
   else if(vol_pending<10)vol_pending<=vol_pending+1'b1;
 1:if(hold)begin if(bri_pending!=0)bri_pending<=bri_pending-1'b1;end
   else if(bri_pending<8)bri_pending<=bri_pending+1'b1;
 2:if(hold)begin if(con_pending!=0)con_pending<=con_pending-1'b1;end
   else if(con_pending<8)con_pending<=con_pending+1'b1;
 3:if(hold)begin vol_pending<=5;bri_pending<=4;con_pending<=4;end
 endcase end
 if(frame_tick)begin
 volume<=gain(vol_pending);vol_level<=vol_pending;brightness<=bri_pending;
 contrast<=con_pending;selected<=sw_stable;hud_show<=show_count!=0;
 end end end
endmodule

// Two cycles, matching the original background pipeline. Signed arithmetic
// implements clamp(((RGB-128)*contrast)/4 + 128 + (brightness-4)*16).
module video_display_adjust(input clk,rst,input [23:0] rgb,
 input [3:0] brightness,contrast,output reg [23:0] adjusted);
 reg signed [13:0] pr,pg,pb;
 reg signed [8:0] offset;
 function [7:0] clamp;input signed [14:0] value;begin
 if(value<0)clamp=0;else if(value>255)clamp=255;else clamp=value[7:0];
 end endfunction
 always @(posedge clk or posedge rst)begin
 if(rst)begin pr<=0;pg<=0;pb<=0;offset<=0;adjusted<=0;end
 else begin
 pr<=($signed({1'b0,rgb[23:16]})-9'sd128)*$signed({1'b0,contrast});
 pg<=($signed({1'b0,rgb[15:8]})-9'sd128)*$signed({1'b0,contrast});
 pb<=($signed({1'b0,rgb[7:0]})-9'sd128)*$signed({1'b0,contrast});
 offset<=($signed({1'b0,brightness})-9'sd4)<<<4;
 adjusted[23:16]<=clamp((pr>>>2)+15'sd128+offset);
 adjusted[15:8]<=clamp((pg>>>2)+15'sd128+offset);
 adjusted[7:0]<=clamp((pb>>>2)+15'sd128+offset);
 end end
endmodule

