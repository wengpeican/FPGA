# Render the parameter HUD Chinese glyphs (SimSun 16x16, 1-bit) into the
# cjk_row function between the BEGIN/END CJK FONT markers of the HUD source,
# plus a scaled preview PNG. Glyph order must match the G_* localparams.
param(
 [string]$OutFile = (Join-Path $PSScriptRoot '../../user_source/hdl_source/osd/display_parameter_ctrl.v'),
 [string]$Preview = (Join-Path $PSScriptRoot 'cjk_font_preview.png')
)
Add-Type -AssemblyName System.Drawing
$chars = '音量亮度对比短按加长减恢复默认'.ToCharArray()
$font = New-Object System.Drawing.Font('SimSun', 16, [System.Drawing.FontStyle]::Regular, [System.Drawing.GraphicsUnit]::Pixel)
$fmt = [System.Drawing.StringFormat]::GenericTypographic
$rows = @()
$scale = 8
$sheet = New-Object System.Drawing.Bitmap(($chars.Count * 18 * $scale), (18 * $scale))
$sg = [System.Drawing.Graphics]::FromImage($sheet)
$sg.Clear([System.Drawing.Color]::FromArgb(16, 32, 48))
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add('// BEGIN CJK FONT')
$lines.Add('// Generated by sim/display_controls/gen_cjk_font.ps1 from SimSun 16x16. Do not edit.')
$lines.Add('// Glyphs: ' + (($chars | ForEach-Object -Begin { $i = 0 } -Process { "$i=$_"; $i++ }) -join ' '))
$lines.Add(' function [15:0] cjk_row;input [3:0] glyph;input [3:0] row;begin case({glyph,row})')
for ($g = 0; $g -lt $chars.Count; $g++) {
 $bmp = New-Object System.Drawing.Bitmap(16, 16)
 $gr = [System.Drawing.Graphics]::FromImage($bmp)
 $gr.Clear([System.Drawing.Color]::Black)
 $gr.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::SingleBitPerPixelGridFit
 $gr.DrawString([string]$chars[$g], $font, [System.Drawing.Brushes]::White, 0, 0, $fmt)
 $gr.Dispose()
 for ($r = 0; $r -lt 16; $r++) {
  $bits = ''
  for ($c = 0; $c -lt 16; $c++) {
   $on = $bmp.GetPixel($c, $r).R -gt 127
   $bits += $(if ($on) { '1' } else { '0' })
   if ($on) {
    $sg.FillRectangle([System.Drawing.Brushes]::White, ($g * 18 + 1 + $c) * $scale, (1 + $r) * $scale, $scale - 1, $scale - 1)
   }
  }
  if ($bits -ne ('0' * 16)) { $lines.Add(("8'h{0:x}{1:x}:cjk_row=16'b{2};" -f $g, $r, $bits)) }
 }
 $bmp.Dispose()
}
$lines.Add(' default:cjk_row=16''d0;endcase end endfunction')
$lines.Add('// END CJK FONT')
$sg.Dispose()
$sheet.Save($Preview, [System.Drawing.Imaging.ImageFormat]::Png)
$sheet.Dispose()
$target = [IO.Path]::GetFullPath($OutFile)
$src = [IO.File]::ReadAllText($target)
$pattern = '(?s)// BEGIN CJK FONT.*?// END CJK FONT'
if ($src -notmatch $pattern) { throw "CJK FONT markers missing in $target" }
$block = $lines -join "`n"
$src = [regex]::Replace($src, $pattern, [System.Text.RegularExpressions.MatchEvaluator]{ param($m) $block })
[IO.File]::WriteAllText($target, $src, (New-Object System.Text.UTF8Encoding($false)))
"glyphs=$($chars.Count) rows=$($lines.Count - 6) -> $target"
